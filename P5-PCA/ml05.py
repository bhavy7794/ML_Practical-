import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split, StratifiedKFold, cross_val_score
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import Pipeline

from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix
)

df = pd.read_csv("/content/Wine_PCA.csv")

print("Dataset loaded successfully!")

display(df.head())

print("Dataset Shape:")
print(df.shape)

print("\nClass Distribution:")
print(df["Wine_Class"].value_counts().sort_index())

print("\nMissing Values:")
print(df.isnull().sum())

feature_names = [
    "Alcohol",
    "Flavanoids",
    "Color_Intensity",
    "Proline",
    "Total_Phenols",
    "Hue"
]

X = df[feature_names]

y = df["Wine_Class"]

print("Features:")
print(X.columns.tolist())

print("\nTarget: Wine_Class")

print("0 = Cultivar 2")
print("1 = Cultivar 3")

print("\nFeature data:")
display(X.head())

print("\nTarget distribution:")
print(y.value_counts())

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training samples:", len(X_train))
print("Testing samples:", len(X_test))

scaler = StandardScaler()

X_train_scaled = scaler.fit_transform(X_train)

X_test_scaled = scaler.transform(X_test)

print("Standardization completed.")

print("\nFirst 5 standardized rows:")
print(X_train_scaled[:5])

pca = PCA(n_components=2)

X_train_pca = pca.fit_transform(X_train_scaled)

X_test_pca = pca.transform(X_test_scaled)

print("Original number of features:", X_train.shape[1])

print("Features after PCA:", X_train_pca.shape[1])

print("\nExplained Variance Ratio:")
print(pca.explained_variance_ratio_)

print("\nTotal Variance Retained:")
print(pca.explained_variance_ratio_.sum())

pca_df = pd.DataFrame(
    X_train_pca,
    columns=["PC1", "PC2"]
)

pca_df["Wine_Class"] = y_train.values

display(pca_df.head())

plt.figure(figsize=(12, 5))

# Before PCA
plt.subplot(1, 2, 1)

plt.scatter(
    X_train_scaled[:, 0],
    X_train_scaled[:, 1],
    c=y_train,
    cmap="coolwarm",
    alpha=0.75,
    edgecolors="k"
)

plt.xlabel("Alcohol (scaled)")
plt.ylabel("Flavanoids (scaled)")
plt.title("Before PCA (First 2 Features)")
plt.colorbar(label="Wine Class")


# After PCA
plt.subplot(1, 2, 2)

plt.scatter(
    X_train_pca[:, 0],
    X_train_pca[:, 1],
    c=y_train,
    cmap="coolwarm",
    alpha=0.75,
    edgecolors="k"
)

plt.xlabel("Principal Component 1")
plt.ylabel("Principal Component 2")
plt.title("After PCA")
plt.colorbar(label="Wine Class")

plt.tight_layout()
plt.show()

model = LogisticRegression(
    random_state=42
)

model.fit(
    X_train_pca,
    y_train
)

print("Logistic Regression model trained successfully!")

y_pred = model.predict(X_test_pca)

y_prob = model.predict_proba(
    X_test_pca
)[:, 1]

print("Predicted Classes:")
print(y_pred)

print("\nPrediction Probabilities:")
print(y_prob[:10])

accuracy = accuracy_score(
    y_test,
    y_pred
)

print(f"Test Accuracy: {accuracy:.2%}")

cv_pipeline = Pipeline([
    ("scaler", StandardScaler()),
    ("pca", PCA(n_components=2)),
    ("clf", LogisticRegression(random_state=42))
])

cv = StratifiedKFold(
    n_splits=5,
    shuffle=True,
    random_state=42
)

cv_scores = cross_val_score(
    cv_pipeline,
    X,
    y,
    cv=cv,
    scoring="accuracy"
)

print("Cross-validation accuracies:")
print(np.round(cv_scores, 3))

print(
    f"\nMean CV Accuracy: "
    f"{cv_scores.mean():.2%}"
)

print(
    f"Standard Deviation: "
    f"{cv_scores.std():.2%}"
)

cm = confusion_matrix(
    y_test,
    y_pred
)

print("Confusion Matrix:")
print(cm)

plt.figure(figsize=(6, 5))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=[
        "Cultivar 2",
        "Cultivar 3"
    ],
    yticklabels=[
        "Cultivar 2",
        "Cultivar 3"
    ]
)

plt.xlabel("Predicted Label")
plt.ylabel("Actual Label")

plt.title("Confusion Matrix")

plt.show()

print("Classification Report:")

print(
    classification_report(
        y_test,
        y_pred,
        target_names=[
            "Cultivar 2",
            "Cultivar 3"
        ]
    )
)

component_loadings = pd.DataFrame(
    pca.components_.T,
    columns=[
        "PC1",
        "PC2"
    ],
    index=feature_names
)

print("PCA Component Loadings:")

display(component_loadings)

plt.figure(figsize=(8, 6))

sns.heatmap(
    component_loadings,
    annot=True,
    cmap="viridis",
    fmt=".2f"
)

plt.title("PCA Component Loadings")

plt.xlabel("Principal Components")
plt.ylabel("Original Features")

plt.tight_layout()
plt.show()

component_loadings.plot(
    kind="bar",
    figsize=(10, 7)
)

plt.title(
    "PCA Component Loadings (Bar Plot)"
)

plt.xlabel("Original Features")

plt.ylabel("Loading Value")

plt.xticks(
    rotation=45,
    ha="right"
)

plt.grid(axis="y")

plt.tight_layout()

plt.show()